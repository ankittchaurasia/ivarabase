create table orders (id bigint generated by default as identity primary key, item text not null, qty int default 1);
insert into orders (item, qty) values ('apple', 10), ('pear', 1), ('kiwi', 7);
alter table orders enable row level security;
create policy anon_read on orders for select to anon using (qty > 5);

create table todos (
  id bigint generated always as identity primary key,
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  title text not null
);
alter table todos enable row level security;
create policy own_select on todos for select to authenticated using (user_id = auth.uid());
create policy own_insert on todos for insert to authenticated with check (user_id = auth.uid());

create function add_numbers(a int, b int) returns int language sql as $$ select a + b $$;

