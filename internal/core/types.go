// TypeScript types for a project's schema, in the same shape as
// `supabase gen types typescript`, so createClient<Database>() type-checks
// queries, inserts, updates, RPC calls and enums.

type tsColumn struct {
	name, tsType           string
	nullable, hasDefault   bool
	identityAlways         bool
	generated, isUpdatable bool
}

type tsRel struct {
	name, refTable string
	cols, refCols  []string
	oneToOne       bool
}

func pgToTS(udt string, enums map[string]string) string {
	if strings.HasPrefix(udt, "_") { // array
		return "(" + pgToTS(strings.TrimPrefix(udt, "_"), enums) + ")[]"
	}
	switch udt {
	case "int2", "int4", "int8", "float4", "float8", "numeric", "oid":
		return "number"
	case "bool":
		return "boolean"
	case "json", "jsonb":
		return "Json"
	case "text", "varchar", "bpchar", "char", "name", "uuid", "date", "time", "timetz", "timestamp", "timestamptz",
		"interval", "inet", "cidr", "macaddr", "bytea", "money", "citext", "tsvector", "xml", "bit", "varbit":
		return "string"
	case "void":
		return "undefined"
	case "record":
		return "Record<string, unknown>"
	}
	if e, ok := enums[udt]; ok {
		return e
	}
	return "unknown"
}

func tsKey(s string) string {
	for i, r := range s {
		if !(r == '_' || r == '$' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (i > 0 && r >= '0' && r <= '9')) {
			return fmt.Sprintf("%q", s)
		}
	}
	return s
}

// generateTypes builds the Database type for the given schemas.
func (a *App) generateTypes(ctx context.Context, slug string, schemas []string) (string, error) {
	db, err := a.projectDB(slug)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("// Generated by IvaraBase for project " + slug + ". Regenerate after schema changes:\n")
	b.WriteString("//   ivarabase db types --project " + slug + " --out database.types.ts\n\n")
	b.WriteString("export type Json =\n  | string\n  | number\n  | boolean\n  | null\n  | { [key: string]: Json | undefined }\n  | Json[]\n\n")
	b.WriteString("export type Database = {\n")
	for _, schema := range schemas {
		if err := writeSchemaTypes(ctx, db, schema, &b); err != nil {
			return "", err
		}
	}
	b.WriteString("}\n")
	b.WriteString(typeHelpers)
	return b.String(), nil
}

func writeSchemaTypes(ctx context.Context, db *sql.DB, schema string, b *strings.Builder) error {
	// enums
	enums := map[string]string{}
	enumDefs := map[string][]string{}
	rows, err := db.QueryContext(ctx, `SELECT t.typname, e.enumlabel FROM pg_type t JOIN pg_enum e ON e.enumtypid=t.oid
		JOIN pg_namespace n ON n.oid=t.typnamespace WHERE n.nspname=$1 ORDER BY t.typname, e.enumsortorder`, schema)
	if err != nil {
		return err
	}
	for rows.Next() {
		var t, l string
		rows.Scan(&t, &l)
		enumDefs[t] = append(enumDefs[t], fmt.Sprintf("%q", l))
	}
	rows.Close()
	for t, ls := range enumDefs {
		enums[t] = strings.Join(ls, " | ")
	}

	// columns of tables and views
	type rel struct {
		kind string
		cols []tsColumn
	}
	rels := map[string]*rel{}
	var relOrder []string
	rows, err = db.QueryContext(ctx, `
		SELECT c.relname, c.relkind::text, a.attname, t.typname, NOT a.attnotnull, a.atthasdef OR a.attidentity <> '' OR a.attgenerated <> '',
		       a.attidentity = 'a', a.attgenerated <> ''
		FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
		JOIN pg_attribute a ON a.attrelid=c.oid AND a.attnum > 0 AND NOT a.attisdropped
		JOIN pg_type t ON t.oid=a.atttypid
		WHERE n.nspname=$1 AND c.relkind IN ('r','p','v','m','f') AND NOT c.relispartition
		ORDER BY c.relname, a.attnum`, schema)
	if err != nil {
		return err
	}
	for rows.Next() {
		var relname, kind, col, typ string
		var c tsColumn
		rows.Scan(&relname, &kind, &col, &typ, &c.nullable, &c.hasDefault, &c.identityAlways, &c.generated)
		c.name, c.tsType = col, pgToTS(typ, enums)
		r := rels[relname]
		if r == nil {
			r = &rel{kind: kind}
			rels[relname] = r
			relOrder = append(relOrder, relname)
		}
		r.cols = append(r.cols, c)
	}
	rows.Close()

	// foreign keys
	fks := map[string][]tsRel{}
	rows, err = db.QueryContext(ctx, `
		SELECT c.conname, cl.relname, rc.relname,
			array(SELECT a.attname FROM unnest(c.conkey) k JOIN pg_attribute a ON a.attrelid=c.conrelid AND a.attnum=k),
			array(SELECT a.attname FROM unnest(c.confkey) k JOIN pg_attribute a ON a.attrelid=c.confrelid AND a.attnum=k),
			EXISTS(SELECT 1 FROM pg_index i WHERE i.indrelid=c.conrelid AND i.indisunique AND i.indkey::int2[] @> c.conkey AND array_length(i.indkey::int2[],1)=array_length(c.conkey,1))
		FROM pg_constraint c JOIN pg_class cl ON cl.oid=c.conrelid JOIN pg_namespace n ON n.oid=cl.relnamespace
		JOIN pg_class rc ON rc.oid=c.confrelid
		WHERE c.contype='f' AND n.nspname=$1 ORDER BY c.conname`, schema)
	if err != nil {
		return err
	}
	for rows.Next() {
		var r tsRel
		var table string
		rows.Scan(&r.name, &table, &r.refTable, pq.Array(&r.cols), pq.Array(&r.refCols), &r.oneToOne)
		fks[table] = append(fks[table], r)
	}
	rows.Close()

	quoteList := func(xs []string) string {
		out := make([]string, len(xs))
		for i, x := range xs {
			out[i] = fmt.Sprintf("%q", x)
		}
		return "[" + strings.Join(out, ", ") + "]"
	}
	writeRels := func(name, ind string) {
		if len(fks[name]) == 0 {
			b.WriteString(ind + "Relationships: []\n")
			return
		}
		b.WriteString(ind + "Relationships: [\n")
		for _, r := range fks[name] {
			fmt.Fprintf(b, "%s  {\n%s    foreignKeyName: %q\n%s    columns: %s\n%s    isOneToOne: %v\n%s    referencedRelation: %q\n%s    referencedColumns: %s\n%s  },\n",
				ind, ind, r.name, ind, quoteList(r.cols), ind, r.oneToOne, ind, r.refTable, ind, quoteList(r.refCols), ind)
		}
		b.WriteString(ind + "]\n")
	}
	writeCols := func(cols []tsColumn, mode string, ind string) {
		b.WriteString("{\n")
		for _, c := range cols {
			t := c.tsType
			if c.nullable {
				t += " | null"
			}
			switch mode {
			case "Row":
				fmt.Fprintf(b, "%s  %s: %s\n", ind, tsKey(c.name), t)
			case "Insert":
				switch {
				case c.identityAlways || c.generated:
					fmt.Fprintf(b, "%s  %s?: never\n", ind, tsKey(c.name))
				case c.nullable || c.hasDefault:
					fmt.Fprintf(b, "%s  %s?: %s\n", ind, tsKey(c.name), t)
				default:
					fmt.Fprintf(b, "%s  %s: %s\n", ind, tsKey(c.name), t)
				}
			case "Update":
				if c.identityAlways || c.generated {
					fmt.Fprintf(b, "%s  %s?: never\n", ind, tsKey(c.name))
				} else {
					fmt.Fprintf(b, "%s  %s?: %s\n", ind, tsKey(c.name), t)
				}
			}
		}
		b.WriteString(ind + "}\n")
	}

	fmt.Fprintf(b, "  %s: {\n", tsKey(schema))
	// Tables
	b.WriteString("    Tables: {\n")
	n := 0
	for _, name := range relOrder {
		r := rels[name]
		if r.kind != "r" && r.kind != "p" && r.kind != "f" {
			continue
		}
		n++
		fmt.Fprintf(b, "      %s: {\n", tsKey(name))
		for _, mode := range []string{"Row", "Insert", "Update"} {
			b.WriteString("        " + mode + ": ")
			writeCols(r.cols, mode, "        ")
		}
		writeRels(name, "        ")
		b.WriteString("      }\n")
	}
	if n == 0 {
		b.WriteString("      [_ in never]: never\n")
	}
	b.WriteString("    }\n")
	// Views
	b.WriteString("    Views: {\n")
	n = 0
	for _, name := range relOrder {
		r := rels[name]
		if r.kind != "v" && r.kind != "m" {
			continue
		}
		n++
		fmt.Fprintf(b, "      %s: {\n        Row: ", tsKey(name))
		writeCols(r.cols, "Row", "        ")
		writeRels(name, "        ")
		b.WriteString("      }\n")
	}
	if n == 0 {
		b.WriteString("      [_ in never]: never\n")
	}
	b.WriteString("    }\n")

	// Functions (callable via rpc)
	b.WriteString("    Functions: {\n")
	rows, err = db.QueryContext(ctx, `
		SELECT p.proname, coalesce(p.proargnames, '{}'), coalesce(p.proargmodes::text[], '{}'),
			array(SELECT format_type(t, NULL) FROM unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) t),
			array(SELECT ty.typname FROM unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) WITH ORDINALITY AS u(t, i) JOIN pg_type ty ON ty.oid=u.t ORDER BY u.i),
			rt.typname, p.proretset, p.pronargdefaults,
			coalesce((SELECT c.relname FROM pg_class c WHERE c.reltype=p.prorettype), '')
		FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace JOIN pg_type rt ON rt.oid=p.prorettype
		WHERE n.nspname=$1 AND p.prokind='f' AND rt.typname NOT IN ('trigger','event_trigger')
		ORDER BY p.proname, p.oid`, schema)
	if err != nil {
		return err
	}
	seen := map[string]bool{}
	n = 0
	for rows.Next() {
		var name, ret, retTable string
		var argNames, modes, fmts, typs []string
		var setof bool
		var nDefaults int
		rows.Scan(&name, pq.Array(&argNames), pq.Array(&modes), pq.Array(&fmts), pq.Array(&typs), &ret, &setof, &nDefaults, &retTable)
		if seen[name] { // overloads: keep the first
			continue
		}
		seen[name] = true
		n++
		var ins []string
		var outs []string
		inCount := 0
		for i := range typs {
			mode := "i"
			if i < len(modes) {
				mode = modes[i]
			}
			if mode == "i" || mode == "b" || mode == "v" {
				inCount++
			}
		}
		inIdx := 0
		for i, t := range typs {
			mode := "i"
			if i < len(modes) {
				mode = modes[i]
			}
			an := fmt.Sprintf("arg%d", i+1)
			if i < len(argNames) && argNames[i] != "" {
				an = argNames[i]
			}
			if mode == "i" || mode == "b" || mode == "v" {
				opt := ""
				if inIdx >= inCount-nDefaults {
					opt = "?"
				}
				ins = append(ins, fmt.Sprintf("%s%s: %s", tsKey(an), opt, pgToTS(t, enums)))
				inIdx++
			}
			if mode == "o" || mode == "b" || mode == "t" {
				outs = append(outs, fmt.Sprintf("%s: %s", tsKey(an), pgToTS(t, enums)))
			}
		}
		returns := pgToTS(ret, enums)
		switch {
		case retTable != "":
			returns = fmt.Sprintf("Database[%q][\"Tables\"][%q][\"Row\"]", schema, retTable)
			if r, ok := rels[retTable]; ok && (r.kind == "v" || r.kind == "m") {
				returns = fmt.Sprintf("Database[%q][\"Views\"][%q][\"Row\"]", schema, retTable)
			}
		case len(outs) > 0:
			returns = "{ " + strings.Join(outs, "; ") + " }"
		}
		if setof {
			returns += "[]"
		}
		args := "Record<PropertyKey, never>"
		if len(ins) > 0 {
			args = "{ " + strings.Join(ins, "; ") + " }"
		}
		fmt.Fprintf(b, "      %s: {\n        Args: %s\n        Returns: %s\n      }\n", tsKey(name), args, returns)
	}
	rows.Close()
	if n == 0 {
		b.WriteString("      [_ in never]: never\n")
	}
	b.WriteString("    }\n")

	// Enums
	b.WriteString("    Enums: {\n")
	names := make([]string, 0, len(enumDefs))
	for t := range enumDefs {
		names = append(names, t)
	}
	sort.Strings(names)
	for _, t := range names {
		fmt.Fprintf(b, "      %s: %s\n", tsKey(t), enums[t])
	}
	if len(names) == 0 {
		b.WriteString("      [_ in never]: never\n")
	}
	b.WriteString("    }\n    CompositeTypes: {\n      [_ in never]: never\n    }\n  }\n")
	return nil
}

const typeHelpers = `
type PublicSchema = Database[Extract<keyof Database, "public">]

export type Tables<T extends keyof (PublicSchema["Tables"] & PublicSchema["Views"])> =
  (PublicSchema["Tables"] & PublicSchema["Views"])[T] extends { Row: infer R } ? R : never

export type TablesInsert<T extends keyof PublicSchema["Tables"]> =
  PublicSchema["Tables"][T] extends { Insert: infer I } ? I : never

export type TablesUpdate<T extends keyof PublicSchema["Tables"]> =
  PublicSchema["Tables"][T] extends { Update: infer U } ? U : never

export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T]
`

func registerTypesOps(r *Registry) {
	r.add(&Op{Name: "db.types", Tag: "database", Method: "GET", Path: "/api/v1/projects/{project}/types", Level: LevelRead,
		Summary:     "TypeScript types for the project's schema (supabase gen types format)",
		Description: "Save as database.types.ts and use createClient<Database>(url, key) for typed queries, inserts, updates and rpc.",
		Params:      []Param{{Name: "project", Type: "string", Required: true}, {Name: "schemas", Type: "array", Desc: "default [public]"}},
		Run: func(c *Ctx, a Args) (any, error) {
			schemas := a.StrList("schemas")
			if len(schemas) == 0 {
				schemas = []string{"public"}
			}
			ts, err := c.App.generateTypes(c, a.Str("project"), schemas)
			if err != nil {
				return nil, sqlError(err)
			}
			return map[string]any{"types": ts, "schemas": schemas}, nil
		}})
}
