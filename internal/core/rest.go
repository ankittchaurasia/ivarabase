var corsAllowHeaders = "authorization, apikey, content-type, content-profile, accept-profile, prefer, range, range-unit, x-client-info, x-upsert, x-supabase-api-version" +
	", tus-resumable, upload-length, upload-metadata, upload-offset, upload-defer-length, upload-concat, x-http-method-override, x-requested-with"

func setCORS(w http.ResponseWriter, r *http.Request) {
	h := w.Header()
	origin := r.Header.Get("Origin")
	if origin == "" {
		origin = "*"
	}
	h.Set("Access-Control-Allow-Origin", origin)
	h.Set("Vary", "Origin")
	h.Set("Access-Control-Allow-Methods", "GET, POST, PUT, PATCH, DELETE, OPTIONS, HEAD")
	h.Set("Access-Control-Allow-Headers", corsAllowHeaders)
	h.Set("Access-Control-Expose-Headers", "Content-Range, Range, Content-Location, Preference-Applied, X-Total-Count"+
		", Location, Tus-Resumable, Tus-Version, Tus-Extension, Tus-Max-Size, Upload-Offset, Upload-Length, Upload-Expires, Upload-Metadata")
	h.Set("Access-Control-Max-Age", "3600")
}

// supaError writes the error shape supabase-js expects from the gateway.
func supaError(w http.ResponseWriter, status int, msg, hint string) {
	writeJSON(w, status, map[string]any{"message": msg, "hint": hint, "code": fmt.Sprint(status)})
}

// handleProject records per-project request metrics around handleProjectInner.
func (s *Server) handleProject(w http.ResponseWriter, r *http.Request) {
	parts := strings.SplitN(strings.TrimPrefix(r.URL.Path, "/proj/"), "/", 3)
	if r.Method == http.MethodOptions || len(parts) < 2 || parts[1] == "realtime" { // websockets live for hours: no latency metric
		s.handleProjectInner(w, r)
		return
	}
	start := time.Now()
	rec := &statusRecorder{ResponseWriter: w, status: 200}
	s.handleProjectInner(rec, r)
	s.app.metrics.observe(parts[0], parts[1], rec.status, time.Since(start))
}

// handleProjectInner serves /proj/<slug>/<service>/... like a Supabase project URL.
func (s *Server) handleProjectInner(w http.ResponseWriter, r *http.Request) {
	setCORS(w, r)
	if r.Method == http.MethodOptions {
		if strings.Contains(r.URL.Path, "/storage/v1/upload/resumable") {
			s.app.tusOptions(w)
		}
		w.WriteHeader(204)
		return
	}
	parts := strings.SplitN(strings.TrimPrefix(r.URL.Path, "/proj/"), "/", 4)
	if len(parts) < 3 || parts[0] == "" {
		supaError(w, 404, "Not found", "project URLs look like /proj/<slug>/rest/v1/<table>")
		return
	}
	slug, service, version := parts[0], parts[1], parts[2]
	rest := "/"
	if len(parts) == 4 {
		rest = "/" + parts[3]
	}
	st, err := s.app.projectAPIState(slug)
	if err != nil {
		supaError(w, 404, "Project not found", "")
		return
	}
	if service == "storage" && version == "v1" && storagePublicPath(r.Method, rest) {
		s.app.metrics.count(slug, "storage")
		s.app.serveStorage(w, r, slug, rest, st.Secret)
		return
	}
	if service == "functions" && version == "v1" {
		s.serveProjectFunction(w, r, slug, st.Secret, rest) // auth decided per function (verify_jwt)
		return
	}
	if service == "auth" && version == "v1" && authPublicPath(r.Method, rest) {
		s.app.metrics.count(slug, "auth")
		s.app.serveAuth(w, r, slug, rest)
		return
	}

	key := r.Header.Get("apikey")
	q := r.URL.Query()
	if key == "" {
		key = q.Get("apikey")
	}
	if key == "" {
		supaError(w, 401, "No API key found in request", "No `apikey` request header or url param was found.")
		return
	}
	claims, err := verifyJWT(st.Secret, key)
	if err != nil || claims["ref"] != slug {
		supaError(w, 401, "Invalid API key", "Double check your project URL and API key.")
		return
	}
	if q.Has("apikey") {
		q.Del("apikey") // PostgREST would treat it as a column filter
		r.URL.RawQuery = q.Encode()
	}
	if r.Header.Get("Authorization") == "" {
		r.Header.Set("Authorization", "Bearer "+key)
	}
	r.Header.Del("Cookie")
	s.app.metrics.count(slug, service)

	switch {
	case service == "rest" && version == "v1":
		p, err := s.app.Rest.ensure(slug)
		if err != nil {
			ae := AsAPIError(err)
			supaError(w, ae.Status, ae.Message, ae.Hint)
			return
		}
		r.URL.Path = rest
		r.URL.RawPath = ""
		p.proxy.ServeHTTP(w, r)
	case service == "auth" && version == "v1":
		s.app.serveAuth(w, r, slug, rest)
	case service == "storage" && version == "v1":
		s.app.serveStorage(w, r, slug, rest, st.Secret)
	case service == "realtime" && version == "v1":
		s.app.serveRealtime(w, r, slug, rest, key)
	default:
		supaError(w, 404, "Unknown service "+service+"/"+version, "available: /rest/v1, /auth/v1, /storage/v1, /functions/v1, /realtime/v1")
	}
}
