// RestRuntime runs one PostgREST process per project that is being used,
// started on the first request and stopped after 10 idle minutes. An idle
// project costs no memory.
type RestRuntime struct {
	app   *App
	mu    sync.Mutex
	procs map[string]*restProc
	lock  sync.Map // slug -> *sync.Mutex, serializes cold starts

	binOnce sync.Once
	bin     string
	version string
}

type restProc struct {
	cmd      *exec.Cmd
	port     int
	lastUsed time.Time
	done     chan struct{}
	stderr   *ringBuf
	proxy    *httputil.ReverseProxy
	started  time.Time
}

func newRestRuntime(a *App) *RestRuntime { return &RestRuntime{app: a, procs: map[string]*restProc{}} }

func (r *RestRuntime) binary() string {
	r.binOnce.Do(func() {
		cands := []string{r.app.Cfg.PostgrestPath}
		if p, err := exec.LookPath("postgrest"); err == nil {
			cands = append(cands, p)
		}
		cands = append(cands, "/opt/homebrew/bin/postgrest", "/usr/local/bin/postgrest", "/usr/bin/postgrest", r.app.Cfg.Path("bin", "postgrest"))
		for _, c := range cands {
			if c != "" && fileExists(c) {
				r.bin = c
				if out, err := exec.Command(c, "--version").CombinedOutput(); err == nil {
					r.version = strings.TrimSpace(strings.SplitN(string(out), "\n", 2)[0])
				}
				return
			}
		}
	})
	return r.bin
}

func (r *RestRuntime) status(slug string) map[string]any {
	r.mu.Lock()
	p := r.procs[slug]
	r.mu.Unlock()
	out := map[string]any{"engine": "postgrest", "available": r.binary() != "", "version": r.version, "running": false}
	if p != nil {
		out["running"] = true
		out["since"] = p.started
		out["idle_s"] = int(time.Since(p.lastUsed).Seconds())
	}
	return out
}

func (r *RestRuntime) Stop(slug string) {
	r.mu.Lock()
	p := r.procs[slug]
	delete(r.procs, slug)
	r.mu.Unlock()
	if p != nil {
		stopRest(p)
	}
}

func (r *RestRuntime) StopAll() {
	r.mu.Lock()
	all := r.procs
	r.procs = map[string]*restProc{}
	r.mu.Unlock()
	for _, p := range all {
		stopRest(p)
	}
}

func stopRest(p *restProc) {
	if p.cmd.Process != nil {
		p.cmd.Process.Signal(os.Interrupt)
	}
	select {
	case <-p.done:
	case <-time.After(3 * time.Second):
		p.cmd.Process.Kill()
	}
}

func (r *RestRuntime) reaper(ctx context.Context) {
	t := time.NewTicker(time.Minute)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			r.mu.Lock()
			var idle []*restProc
			for k, p := range r.procs {
				if time.Since(p.lastUsed) > 10*time.Minute {
					idle = append(idle, p)
					delete(r.procs, k)
				}
			}
			r.mu.Unlock()
			for _, p := range idle {
				stopRest(p)
			}
		}
	}
}

// ensure returns a running PostgREST for the project.
func (r *RestRuntime) ensure(slug string) (*restProc, error) {
	r.mu.Lock()
	if p, ok := r.procs[slug]; ok {
		select {
		case <-p.done:
			delete(r.procs, slug)
		default:
			p.lastUsed = time.Now()
			r.mu.Unlock()
			return p, nil
		}
	}
	r.mu.Unlock()

	lk, _ := r.lock.LoadOrStore(slug, &sync.Mutex{})
	lk.(*sync.Mutex).Lock()
	defer lk.(*sync.Mutex).Unlock()
	r.mu.Lock()
	if p, ok := r.procs[slug]; ok {
		r.mu.Unlock()
		return p, nil
	}
	r.mu.Unlock()

	bin := r.binary()
	if bin == "" {
		return nil, &APIError{Status: 503, Code: "postgrest_missing", Message: "PostgREST is not installed on the server",
			Hint: "macOS: brew install postgrest. Linux: download the static binary from github.com/PostgREST/postgrest/releases into /usr/local/bin (or set postgrest_path in config.json)"}
	}
	st, err := r.app.projectAPIState(slug)
	if err != nil {
		return nil, err
	}
	port, err := freePort()
	if err != nil {
		return nil, err
	}
	admin, err := freePort()
	if err != nil {
		return nil, err
	}
	pg := r.app.PG
	dbURI := fmt.Sprintf("postgres://%s:%s@%s:%d/%s?sslmode=%s&application_name=ivarabase-rest",
		url.QueryEscape(authenticatorRole(slug)), url.QueryEscape(st.AuthPW), pg.Host, pg.Port, url.PathEscape(slug), pg.SSLMode)
	conf := fmt.Sprintf(`# generated by ivarabase - rewritten on every start
db-uri = %q
db-schemas = "public"
db-extra-search-path = "public, extensions"
db-anon-role = "anon"
db-pool = 5
db-pool-max-idletime = 60
db-max-rows = 1000
db-channel-enabled = true
jwt-secret = %q
openapi-mode = "follow-privileges"
server-host = "127.0.0.1"
server-port = %d
admin-server-port = %d
log-level = "error"
`, dbURI, string(st.Secret), port, admin)
	dir := r.app.Cfg.Path("run", "rest")
	os.MkdirAll(dir, 0o700)
	confPath := filepath.Join(dir, slug+".conf")
	if err := os.WriteFile(confPath, []byte(conf), 0o600); err != nil {
		return nil, err
	}
	cmd := exec.Command(bin, confPath)
	cmd.Env = []string{"PATH=/usr/bin:/bin", "LANG=C", "LC_ALL=C"}
	ring := &ringBuf{max: 16 * 1024}
	cmd.Stdout = ring
	cmd.Stderr = ring
	if err := cmd.Start(); err != nil {
		return nil, err
	}
	p := &restProc{cmd: cmd, port: port, lastUsed: time.Now(), started: time.Now(), done: make(chan struct{}), stderr: ring}
	go func() { cmd.Wait(); close(p.done) }()

	ready := false
	deadline := time.Now().Add(25 * time.Second)
	client := &http.Client{Timeout: time.Second}
	for time.Now().Before(deadline) {
		select {
		case <-p.done:
			return nil, &APIError{Status: 502, Code: "postgrest_crashed", Message: "PostgREST exited during startup", Hint: tail(ring.String(), 800)}
		default:
		}
		if resp, err := client.Get(fmt.Sprintf("http://127.0.0.1:%d/ready", admin)); err == nil {
			resp.Body.Close()
			if resp.StatusCode == 200 {
				ready = true
				break
			}
		}
		time.Sleep(150 * time.Millisecond)
	}
	if !ready {
		stopRest(p)
		return nil, &APIError{Status: 504, Code: "postgrest_start_timeout", Message: "PostgREST did not become ready", Hint: tail(ring.String(), 800)}
	}

	target, _ := url.Parse(fmt.Sprintf("http://127.0.0.1:%d", port))
	p.proxy = httputil.NewSingleHostReverseProxy(target)
	p.proxy.ModifyResponse = func(res *http.Response) error {
		for k := range res.Header {
			if strings.HasPrefix(strings.ToLower(k), "access-control-") {
				res.Header.Del(k) // the gateway sets CORS once
			}
		}
		return nil
	}
	p.proxy.ErrorHandler = func(w http.ResponseWriter, req *http.Request, err error) {
		writeError(w, &APIError{Status: 502, Code: "rest_unavailable", Message: err.Error(), Hint: tail(ring.String(), 400)})
	}
	r.mu.Lock()
	r.procs[slug] = p
	r.mu.Unlock()
	return p, nil
}

