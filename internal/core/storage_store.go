// File storage for projects (Supabase storage compatible). Object metadata
// lives in each project's `storage` schema with Supabase's table names, and
// access is decided by row level security on storage.objects - so Supabase
// storage policies work unchanged. File bytes live in a backend: local disk
// (default) or an S3-compatible bucket. Bytes are stored by object id, so
// renames and moves never touch the files.

const storageSchemaSQL = `
CREATE SCHEMA IF NOT EXISTS storage;
CREATE TABLE IF NOT EXISTS storage.buckets (
	id text PRIMARY KEY,
	name text NOT NULL UNIQUE,
	owner uuid,
	public boolean NOT NULL DEFAULT false,
	file_size_limit bigint,
	allowed_mime_types text[],
	created_at timestamptz NOT NULL DEFAULT now(),
	updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS storage.objects (
	id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
	bucket_id text NOT NULL REFERENCES storage.buckets(id),
	name text NOT NULL,
	owner uuid,
	metadata jsonb,
	created_at timestamptz NOT NULL DEFAULT now(),
	updated_at timestamptz NOT NULL DEFAULT now(),
	last_accessed_at timestamptz NOT NULL DEFAULT now(),
	path_tokens text[] GENERATED ALWAYS AS (string_to_array(name, '/')) STORED,
	UNIQUE (bucket_id, name)
);
CREATE INDEX IF NOT EXISTS objects_bucket_name ON storage.objects (bucket_id, name text_pattern_ops);
ALTER TABLE storage.buckets ENABLE ROW LEVEL SECURITY;
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
CREATE OR REPLACE FUNCTION storage.foldername(name text) RETURNS text[] LANGUAGE sql IMMUTABLE AS $$
	SELECT (string_to_array(name, '/'))[1:array_length(string_to_array(name, '/'), 1) - 1] $$;
CREATE OR REPLACE FUNCTION storage.filename(name text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
	SELECT (string_to_array(name, '/'))[array_length(string_to_array(name, '/'), 1)] $$;
CREATE OR REPLACE FUNCTION storage.extension(name text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
	SELECT CASE WHEN storage.filename(name) LIKE '%.%' THEN lower(reverse(split_part(reverse(storage.filename(name)), '.', 1))) ELSE '' END $$;
`

// ensureStorageSchema creates the storage tables as the project role and
// grants the API roles access - row level security then decides per row.
func (a *App) ensureStorageSchema(slug string) error {
	db, err := a.projectDB(slug)
	if err != nil {
		return err
	}
	if _, err := db.Exec(storageSchemaSQL); err != nil {
		return fmt.Errorf("storage schema: %w", err)
	}
	roles := fmt.Sprintf("%s, %s, %s", roleAnon, roleAuthed, roleService)
	for _, q := range []string{
		`GRANT USAGE ON SCHEMA storage TO ` + roles,
		`GRANT ALL ON storage.buckets, storage.objects TO ` + roles,
		`GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA storage TO ` + roles,
	} {
		if _, err := db.Exec(q); err != nil {
			return fmt.Errorf("storage grants: %w", err)
		}
	}
	return nil
}

// ---------------------------------------------------------------- settings

type StorageConfig struct {
	Backend       string   `json:"backend"` // "local" | "s3"
	MaxFileSizeMB int      `json:"max_file_size_mb"`
	S3            S3Config `json:"s3"`
}

func (a *App) storageConfig() StorageConfig {
	c := StorageConfig{Backend: "local", MaxFileSizeMB: 50}
	a.getSetting("storage_config", &c)
	if c.Backend != "s3" || !c.S3.configured() {
		c.Backend = "local"
	}
	if c.MaxFileSizeMB <= 0 {
		c.MaxFileSizeMB = 50
	}
	return c
}

// ---------------------------------------------------------------- backends

type storageBackend interface {
	put(ctx context.Context, slug, bucket, id string, r io.Reader, size int64) (int64, error)
	// serve writes the object to w, honouring Range / conditional headers.
	serve(w http.ResponseWriter, r *http.Request, slug, bucket, id, contentType, etag string, modified time.Time) error
	open(ctx context.Context, slug, bucket, id string) (io.ReadCloser, error)
	remove(ctx context.Context, slug, bucket, id string) error
	copy(ctx context.Context, slug, bucket, fromID, toID string) error
	name() string
}

func (a *App) storageBackend() storageBackend {
	c := a.storageConfig()
	if c.Backend == "s3" {
		return &s3Backend{cfg: c.S3}
	}
	return &localBackend{root: a.Cfg.Path("storage")}
}

type localBackend struct{ root string }

func (b *localBackend) name() string { return "local" }

func (b *localBackend) path(slug, bucket, id string) string {
	// bucket ids and object ids are validated / generated by us, never raw user paths
	return filepath.Join(b.root, slug, safeSegment(bucket), id)
}

func safeSegment(s string) string {
	return strings.NewReplacer("/", "_", "\\", "_", "..", "_").Replace(s)
}

func (b *localBackend) put(ctx context.Context, slug, bucket, id string, r io.Reader, size int64) (int64, error) {
	p := b.path(slug, bucket, id)
	if err := os.MkdirAll(filepath.Dir(p), 0o700); err != nil {
		return 0, err
	}
	tmp := p + ".part" + randHex(4)
	f, err := os.OpenFile(tmp, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o600)
	if err != nil {
		return 0, err
	}
	n, err := io.Copy(f, r)
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		os.Remove(tmp)
		return n, err
	}
	return n, os.Rename(tmp, p)
}

func (b *localBackend) serve(w http.ResponseWriter, r *http.Request, slug, bucket, id, contentType, etag string, modified time.Time) error {
	f, err := os.Open(b.path(slug, bucket, id))
	if err != nil {
		return err
	}
	defer f.Close()
	if contentType != "" {
		w.Header().Set("Content-Type", contentType)
	}
	if etag != "" {
		w.Header().Set("ETag", etag)
	}
	http.ServeContent(w, r, "", modified, f) // Range, If-None-Match, If-Modified-Since
	return nil
}

func (b *localBackend) open(ctx context.Context, slug, bucket, id string) (io.ReadCloser, error) {
	return os.Open(b.path(slug, bucket, id))
}

func (b *localBackend) remove(ctx context.Context, slug, bucket, id string) error {
	err := os.Remove(b.path(slug, bucket, id))
	if os.IsNotExist(err) {
		return nil
	}
	return err
}

func (b *localBackend) copy(ctx context.Context, slug, bucket, fromID, toID string) error {
	src, err := os.Open(b.path(slug, bucket, fromID))
	if err != nil {
		return err
	}
	defer src.Close()
	_, err = b.put(ctx, slug, bucket, toID, src, -1)
	return err
}

type s3Backend struct{ cfg S3Config }

func (b *s3Backend) name() string { return "s3" }

func (b *s3Backend) key(slug, bucket, id string) string {
	return "storage/" + slug + "/" + safeSegment(bucket) + "/" + id
}

func (b *s3Backend) put(ctx context.Context, slug, bucket, id string, r io.Reader, size int64) (int64, error) {
	if size < 0 {
		// S3 needs a length: spool unknown-size bodies to a temp file first
		f, err := os.CreateTemp("", "ivb-up-")
		if err != nil {
			return 0, err
		}
		defer os.Remove(f.Name())
		defer f.Close()
		n, err := io.Copy(f, r)
		if err != nil {
			return n, err
		}
		f.Seek(0, 0)
		r, size = f, n
	}
	if ra, ok := r.(io.ReaderAt); ok && size > s3MultipartMin {
		return size, b.cfg.putMultipart(ctx, b.cfg.key(b.key(slug, bucket, id)), ra, size)
	}
	resp, err := b.cfg.request(ctx, "PUT", b.cfg.key(b.key(slug, bucket, id)), nil, r, size)
	if err != nil {
		return 0, err
	}
	resp.Body.Close()
	return size, nil
}

func (b *s3Backend) serve(w http.ResponseWriter, r *http.Request, slug, bucket, id, contentType, etag string, modified time.Time) error {
	if etag != "" && r.Header.Get("If-None-Match") == etag {
		w.WriteHeader(http.StatusNotModified)
		return nil
	}
	resp, err := b.cfg.requestHeaders(r.Context(), "GET", b.cfg.key(b.key(slug, bucket, id)), map[string]string{"Range": r.Header.Get("Range")})
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	for _, h := range []string{"Content-Length", "Content-Range", "Accept-Ranges"} {
		if v := resp.Header.Get(h); v != "" {
			w.Header().Set(h, v)
		}
	}
	if contentType != "" {
		w.Header().Set("Content-Type", contentType)
	}
	if etag != "" {
		w.Header().Set("ETag", etag)
	}
	w.Header().Set("Last-Modified", modified.UTC().Format(http.TimeFormat))
	w.WriteHeader(resp.StatusCode)
	_, err = io.Copy(w, resp.Body)
	return err
}

func (b *s3Backend) open(ctx context.Context, slug, bucket, id string) (io.ReadCloser, error) {
	resp, err := b.cfg.request(ctx, "GET", b.cfg.key(b.key(slug, bucket, id)), nil, nil, 0)
	if err != nil {
		return nil, err
	}
	return resp.Body, nil
}

func (b *s3Backend) remove(ctx context.Context, slug, bucket, id string) error {
	return b.cfg.Delete(ctx, b.key(slug, bucket, id))
}

func (b *s3Backend) copy(ctx context.Context, slug, bucket, fromID, toID string) error {
	rc, err := b.open(ctx, slug, bucket, fromID)
	if err != nil {
		return err
	}
	defer rc.Close()
	_, err = b.put(ctx, slug, bucket, toID, rc, -1)
	return err
}

// requestHeaders is a GET with extra (unsigned) headers such as Range.
func (s S3Config) requestHeaders(ctx context.Context, method, key string, extra map[string]string) (*http.Response, error) {
	return s.requestWith(ctx, method, key, url.Values{}, nil, 0, extra)
}

// ---------------------------------------------------------------- role-scoped SQL

var apiPools sync.Map // slug -> *sql.DB connected as <slug>_authenticator

func (a *App) apiDB(slug string) (*sql.DB, error) {
	if v, ok := apiPools.Load(slug); ok {
		return v.(*sql.DB), nil
	}
	st, err := a.projectAPIState(slug)
	if err != nil {
		return nil, err
	}
	db, err := a.PG.Open(authenticatorRole(slug), st.AuthPW, slug)
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(6)
	db.SetMaxIdleConns(2)
	db.SetConnMaxIdleTime(time.Minute)
	if prev, loaded := apiPools.LoadOrStore(slug, db); loaded {
		db.Close()
		return prev.(*sql.DB), nil
	}
	return db, nil
}

func closeAPIDB(slug string) {
	if v, ok := apiPools.LoadAndDelete(slug); ok {
		v.(*sql.DB).Close()
	}
}

// asRole runs fn in a transaction as the caller's database role with the
// JWT claims set, exactly like PostgREST does, so row level security applies.
func (a *App) asRole(ctx context.Context, slug string, claims map[string]any, fn func(tx *sql.Tx) error) error {
	role, _ := claims["role"].(string)
	switch role {
	case roleAnon, roleAuthed, roleService:
	default:
		return storageErr(403, "Unauthorized", "invalid role in JWT")
	}
	db, err := a.apiDB(slug)
	if err != nil {
		return err
	}
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	cj, _ := jsonMarshal(claims)
	sub, _ := claims["sub"].(string)
	if _, err := tx.ExecContext(ctx, `SET LOCAL ROLE `+pq.QuoteIdentifier(role)); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, `SELECT set_config('request.jwt.claims', $1, true), set_config('request.jwt.claim.sub', $2, true), set_config('request.jwt.claim.role', $3, true)`,
		cj, sub, role); err != nil {
		return err
	}
	if err := fn(tx); err != nil {
		return err
	}
	return tx.Commit()
}
